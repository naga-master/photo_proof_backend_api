def validate_setup():
    """Validate that all required files exist."""
    print_header("5. Validating Setup")
    
    base_path = Path(__file__).parent
    
    checks = [
        (".env", "Environment configuration"),
        ("app/services/auth_service.py", "Auth service"),
        ("app/routers/auth.py", "Auth router"),
        ("app/routers/upload.py", "Upload router"),
        ("app/routers/comments.py", "Comments router"),
        ("app/routers/projects_template.py", "Template router"),
        ("seed_data.py", "Seed script"),
    ]
    
    all_valid = True
    for file_path, description in checks:
        full_path = base_path / file_path
        if full_path.exists():
            print(f"  ✅ {description}: {file_path}")
        else:
            print(f"  ❌ {description}: {file_path} NOT FOUND")
            all_valid = False
    
    return all_valid


