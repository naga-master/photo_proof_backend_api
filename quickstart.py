def update_auth_service():
    """Update auth_service.py to read from environment."""
    print_header("2. Updating Auth Service")
    
    auth_service_path = Path(__file__).parent / "app" / "services" / "auth_service.py"
    
    if not auth_service_path.exists():
        print(f"⚠️  Auth service not found: {auth_service_path}")
        return
    
    with open(auth_service_path, "r") as f:
        content = f.read()
    
    # Check if already updated
    if "load_dotenv()" in content:
        print("✅ Auth service already configured for environment variables")
        return
    
    # Update imports and configuration
    old_imports = 'from jose import JWTError, jwt'
    new_imports = '''from jose import JWTError, jwt
import os
from dotenv import load_dotenv

load_dotenv()'''
    
    old_config = '''# Configuration
SECRET_KEY = "YOUR_SECRET_KEY_HERE"  # TODO: Move to environment variables
ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_MINUTES = 60 * 24  # 24 hours'''
    
    new_config = '''# Configuration from environment
SECRET_KEY = os.getenv("SECRET_KEY", "YOUR_SECRET_KEY_HERE")
ALGORITHM = os.getenv("ALGORITHM", "HS256")
ACCESS_TOKEN_EXPIRE_MINUTES = int(os.getenv("ACCESS_TOKEN_EXPIRE_MINUTES", "1440"))'''
    
    content = content.replace(old_imports, new_imports)
    content = content.replace(old_config, new_config)
    
    with open(auth_service_path, "w") as f:
        f.write(content)
    
    print(f"✅ Updated auth service to read from environment")


